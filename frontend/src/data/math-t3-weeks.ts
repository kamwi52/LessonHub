import type { WeekPlan } from './ict-curriculum';

type WT = WeekPlan['type'];
const TEXTBOOK = ['Textbook', 'Calculator', 'Graph paper', 'Ruler', 'Whiteboard & markers'];

function wk(
  week: number, type: WT, title: string, focus: string,
  objectives: string[], starter: string, development: string[], plenary: string,
  resources: string[], homework?: string, assessment?: string,
): WeekPlan {
  return { week, type, title, focus, objectives, starter, development, plenary, resources, homework, assessment };
}

